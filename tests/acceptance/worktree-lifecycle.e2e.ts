const exists = async (path: string) => access(path).then(() => true, () => false);

test('real worktree prepare and replay preserve branch scope and clean only the recorded owned checkout', async ({ processes }) => {
  const { root } = processes;
  const repo = await repository(root, 'source');
  const foreign = await repository(root, 'foreign');
  const updater = join(root, 'updater');
  await git(root, root, 'clone', '--branch', 'beta', repo.origin, updater);
  await git(root, repo.checkout, 'config', '--unset-all', 'remote.origin.fetch');
  const stale = await git(root, repo.checkout, 'rev-parse', 'origin/beta');
  await writeFile(join(updater, 'update.txt'), 'Remote base advanced\n');
  await git(root, updater, 'add', 'update.txt');
  await git(root, updater, 'commit', '-m', 'Advance remote base');
  await git(root, updater, 'push', 'origin', 'beta');
  const current = await git(root, updater, 'rev-parse', 'HEAD');
  expect(current).not.toBe(stale);
  const factory = processes.factory();
  const client = await factory.client();
  const wp = await workPackage(client, repo.origin, 'feature/owned');
  const args = { work_package_id: wp, target_repo_root: repo.checkout };
  await client.reject('prepare_work_package_worktree', { ...args, target_repo_root: foreign.checkout }, 'target_repo_root_scope_mismatch');
  await client.reject('prepare_work_package_worktree', { ...args, branch: 'feature/wrong' }, 'branch_scope_mismatch');
  const prepared = await client.call('prepare_work_package_worktree', args);
  const path = prepared.worktree.path;
  expect(prepared.worktree.status).toBe('prepared');
  expect(prepared.work_package.worktree_path).toBe(path);
  expect(await git(root, path, 'branch', '--show-current')).toBe('feature/owned');
  expect(await git(root, path, 'rev-parse', 'HEAD')).toBe(await git(root, repo.checkout, 'rev-parse', 'origin/beta'));
  expect(await git(root, path, 'rev-parse', 'HEAD')).toBe(current);
  expect((await client.call('prepare_work_package_worktree', args)).worktree.path).toBe(path);
  expect((await client.call('prepare_work_package_worktree', args)).worktree.status).toBe('already_prepared');
  const clone = join(root, 'same-origin');
  await git(root, root, 'clone', '--branch', 'beta', repo.origin, clone);
  await writeFile(join(path, 'untracked.txt'), 'Owned disposable work\n');
  await writeFile(join(clone, 'unrelated.txt'), 'Keep foreign clone content\n');
  await client.reject('cleanup_work_package_worktree', { ...args, target_repo_root: clone }, 'invalid_worktree_path');
  await client.reject('cleanup_work_package_worktree', { ...args, target_repo_root: foreign.checkout }, 'target_repo_root_scope_mismatch');
  expect(await readFile(join(path, 'untracked.txt'), 'utf8')).toBe('Owned disposable work\n');
  expect(await readFile(join(clone, 'unrelated.txt'), 'utf8')).toBe('Keep foreign clone content\n');
  const cleaned = await client.call('cleanup_work_package_worktree', args);
  expect(cleaned.worktree.status).toBe('cleaned');
  expect(cleaned.work_package.worktree_path).toBeUndefined();
  expect(await exists(path)).toBe(false);
  expect(await readFile(join(clone, 'unrelated.txt'), 'utf8')).toBe('Keep foreign clone content\n');
  expect(await readFile(join(foreign.checkout, 'README.md'), 'utf8')).toBe('Initial fixture content\n');
  expect((await client.call('cleanup_work_package_worktree', args)).worktree.status).toBe('already_clean');
  const again = await client.call('prepare_work_package_worktree', args);
  expect(again.worktree.status).toBe('prepared');
  expect((await client.call('cleanup_work_package_worktree', args)).worktree.status).toBe('cleaned');
  await git(root, repo.checkout, 'checkout', 'feature/owned');
  await writeFile(join(repo.checkout, 'stale.txt'), 'Preserve divergent local work\n');
  await git(root, repo.checkout, 'add', 'stale.txt');
  await git(root, repo.checkout, 'commit', '-m', 'Local divergent work');
  const divergent = await git(root, repo.checkout, 'rev-parse', 'HEAD');
  await git(root, repo.checkout, 'checkout', 'beta');
  await client.reject('prepare_work_package_worktree', args, 'stale_existing_branch');
  expect(await git(root, repo.checkout, 'rev-parse', 'feature/owned')).toBe(divergent);
  expect(await exists(path)).toBe(false);
});

test('outside-root path substitution is refused without deleting unrelated content and recovery cleans the owned path', async ({ processes }) => {
  const { root } = processes;
  const repo = await repository(root, 'source');
  const factory = processes.factory();
  const client = await factory.client();
  const wp = await workPackage(client, repo.origin, 'feature/safe-path');
  const args = { work_package_id: wp, target_repo_root: repo.checkout };
  const path = (await client.call('prepare_work_package_worktree', args)).worktree.path;
  const saved = `${path}-saved`;
  const unrelated = join(root, 'unrelated');
  await mkdir(unrelated);
  await writeFile(join(unrelated, 'keep.txt'), 'Unrelated data\n');
  await rename(path, saved);
  await symlink(unrelated, path, 'dir');
  try {
    await client.reject('cleanup_work_package_worktree', args, 'unsafe_worktree_path');
    expect(await readFile(join(unrelated, 'keep.txt'), 'utf8')).toBe('Unrelated data\n');
  } finally {
    await rm(path);
    await rename(saved, path);
  }
  const replay = await client.call('prepare_work_package_worktree', args);
  expect(replay.worktree.status).toBe('already_prepared');
  expect(replay.worktree.path).toBe(path);
  expect((await client.call('cleanup_work_package_worktree', args)).worktree.status).toBe('cleaned');
  expect(await exists(path)).toBe(false);
  expect(await readFile(join(unrelated, 'keep.txt'), 'utf8')).toBe('Unrelated data\n');
});

test('missing metadata recovery refuses unrelated non-Git contents and preserves ambient repository files', async ({ processes }) => {
  const { root } = processes;
  const repo = await repository(root, 'source');
  const factory = processes.factory();
  const client = await factory.client();
  const wp = await workPackage(client, repo.origin, 'feature/metadata');
  const args = { work_package_id: wp, target_repo_root: repo.checkout };
  const path = (await client.call('prepare_work_package_worktree', args)).worktree.path;
  const clone = join(root, 'same-name', 'source');
  await git(root, root, 'clone', '--branch', 'beta', repo.origin, clone);
  await rm(path, { recursive: true });
  await client.reject('cleanup_work_package_worktree', { ...args, target_repo_root: clone }, 'invalid_worktree_path');
  expect(await git(root, repo.checkout, 'worktree', 'list', '--porcelain')).toContain(path);
  await mkdir(path);
  await client.reject('prepare_work_package_worktree', args, 'invalid_worktree_path');
  await writeFile(join(path, 'unrelated.txt'), 'Not disposable Git content\n');
  await git(root, factory.home, 'init');
  await writeFile(join(factory.home, 'ambient.txt'), 'Ambient parent data\n');
  await client.reject('cleanup_work_package_worktree', args, 'invalid_worktree_path');
  expect(await readFile(join(path, 'unrelated.txt'), 'utf8')).toBe('Not disposable Git content\n');
  await rm(join(path, 'unrelated.txt'));
  expect((await client.call('cleanup_work_package_worktree', args)).worktree.status).toBe('stale_record_cleared');
  expect(await exists(path)).toBe(false);
  const second = (await client.call('prepare_work_package_worktree', args)).worktree.path;
  await rm(second, { recursive: true });
  await mkdir(second);
  await writeFile(join(second, '.git'), 'gitdir: missing-git-dir\n');
  expect((await client.call('cleanup_work_package_worktree', args)).worktree.status).toBe('stale_record_cleared');
  const third = (await client.call('prepare_work_package_worktree', args)).worktree.path;
  await rm(third, { recursive: true });
  await writeFile(third, 'Not a directory\n');
  await client.reject('cleanup_work_package_worktree', args, 'invalid_worktree_path');
  expect(await readFile(third, 'utf8')).toBe('Not a directory\n');
  await rm(third);
  expect((await client.call('cleanup_work_package_worktree', args)).worktree.status).toBe('stale_record_cleared');
  expect(await readFile(join(factory.home, 'ambient.txt'), 'utf8')).toBe('Ambient parent data\n');
});

test('deleting a goal preserves its cleanup obligation across a stopped backend and removes only its owned tree', async ({ processes }) => {
  const { root } = processes;
  const repo = await repository(root, 'source');
  let factory = processes.factory();
  let client = await factory.client();
  const wp = await workPackage(client, repo.origin, 'feature/deleted');
  const request = (await client.call('list_work_requests')).work_requests[0].id;
  const path = (await client.call('prepare_work_package_worktree', { work_package_id: wp, target_repo_root: repo.checkout })).worktree.path;
  await git(root, repo.checkout, 'worktree', 'lock', path);
  expect((await client.operator(`${requestPath(request)}/delete`, {})).status).toBe(200);
  expect((await client.operator(`${requestPath(request)}/restore`, {})).status).toBe(404);
  expect(await exists(path)).toBe(true);
  await factory.stop();
  await git(root, repo.checkout, 'worktree', 'unlock', path);
  factory = processes.factory();
  client = await factory.client();
  await expect.poll(() => exists(path), { timeout: 30_000 }).toBe(false);
  expect((await client.call('list_work_requests')).work_requests).toEqual([]);
  expect(await readFile(join(repo.checkout, 'README.md'), 'utf8')).toBe('Initial fixture content\n');
});

test('offline snapshot lifecycle changes leave copied live worktree paths and source history untouched', async ({ processes }) => {
  const { root } = processes;
  const repo = await repository(root, 'source');
  const source = processes.factory();
  const architect = await source.client();
  const wp = await workPackage(architect, repo.origin, 'feature/offline');
  const request = (await architect.call('list_work_requests')).work_requests[0].id;
  const args = { work_package_id: wp, target_repo_root: repo.checkout };
  const path = (await architect.call('prepare_work_package_worktree', args)).worktree.path;
  await writeFile(join(path, 'keep.txt'), 'Source worktree content\n');
  await git(root, repo.checkout, 'worktree', 'lock', path);
  expect((await architect.call('cleanup_work_package_worktree', args)).worktree.status).toBe('cleanup_queued');
  await source.stop();
  const database = await snapshot(source);
  const offline = processes.factory('offline', { database, offline: true });
  const client = new Client(await offline.endpoint, offline.receipt);
  for (const [action, body] of [['state', { state: 'completed' }], ['archive', {}], ['restore', {}], ['delete', {}]] as const) {
    expect((await client.operator(`${requestPath(request)}/${action}`, body)).status).toBe(200);
    expect(await readFile(join(path, 'keep.txt'), 'utf8')).toBe('Source worktree content\n');
  }
  await offline.stop();
  const restarted = processes.factory();
  const original = await restarted.client();
  expect((await original.call('list_work_requests')).work_requests.map((row: any) => row.id)).toContain(request);
  expect(await readFile(join(path, 'keep.txt'), 'utf8')).toBe('Source worktree content\n');
  await git(root, repo.checkout, 'worktree', 'unlock', path);
});

test('a real Git removal obstruction preserves the worktree and a later cleanup recovers after restart', async ({ processes }) => {
  const { root } = processes;
  const repo = await repository(root, 'source');
  let factory = processes.factory();
  let client = await factory.client();
  const wp = await workPackage(client, repo.origin, 'feature/recovery');
  const args = { work_package_id: wp, target_repo_root: repo.checkout };
  const path = (await client.call('prepare_work_package_worktree', args)).worktree.path;
  await git(root, repo.checkout, 'worktree', 'lock', path);
  const failed = await client.rpc('tools/call', { name: 'cleanup_work_package_worktree', arguments: args });
  expect(failed.error).toBeUndefined();
  expect(failed.result.structuredContent.worktree.status).toBe('cleanup_queued');
  expect(await exists(path)).toBe(true);
  expect(failed.result.structuredContent.work_package.worktree_path).toBe(path);
  await factory.stop();
  await git(root, repo.checkout, 'worktree', 'unlock', path);
  factory = processes.factory();
  client = await factory.client();
  await client.call('claim_local_architect_assignment', { work_request_id: (await client.call('list_work_requests')).work_requests[0].id, claimed_by: 'acceptance-architect' });
  const recovered = await client.call('cleanup_work_package_worktree', args);
  expect(['cleaned', 'already_clean']).toContain(recovered.worktree.status);
  expect(recovered.work_package.worktree_path).toBeUndefined();
  expect(await exists(path)).toBe(false);
  expect(await readFile(join(repo.checkout, 'README.md'), 'utf8')).toBe('Initial fixture content\n');
});
